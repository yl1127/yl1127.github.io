        const renderLearningPlatformBlock = (container, { title, note, link, heading, items, itemMeta }) => {
            const block = document.createElement("div");
            block.className = "learning-platform-block";

            const platform = document.createElement("h3");
            platform.textContent = title;

            const noteEl = document.createElement("p");
            noteEl.className = "learning-platform-note";
            noteEl.textContent = note;
            if (link) {
                noteEl.append(" ");
                const noteLink = document.createElement("a");
                noteLink.href = link.href;
                noteLink.target = "_blank";
                noteLink.rel = "noopener noreferrer";
                noteLink.textContent = link.text;
                noteEl.appendChild(noteLink);
            }

            const courseHeading = document.createElement("h4");
            courseHeading.textContent = `${heading} · ${items.length}`;

            const courseList = document.createElement("ul");
            courseList.className = "course-list";
            items.forEach((itemData) => {
                const item = document.createElement("li");
                const titleEl = document.createElement("strong");
                const metaEl = document.createElement("span");
                titleEl.textContent = itemData[0];
                metaEl.textContent = itemMeta(itemData);
                item.append(titleEl, metaEl);
                courseList.appendChild(item);
            });

            const courseListWrap = document.createElement("div");
            courseListWrap.className = "course-list-wrap";
            courseListWrap.appendChild(courseList);

            block.append(platform, noteEl, courseHeading, courseListWrap);
            container.appendChild(block);
        };

